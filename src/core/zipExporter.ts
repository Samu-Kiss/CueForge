import JSZip from 'jszip';
import { CompiledShow, ExportConfiguration } from '../types/cueforge';
import { generateEnhancedMa3ExportBundle } from './ma3AppearanceAndMarkers';

export interface ZipExportOptions {
  includeCueAppearances?: boolean;
  baseAppearancePoolId?: number;
  includeMarkerTrack?: boolean;
}

/**
 * Builds a ZIP archive formatted to match the exact grandMA3 USB drive directory structure:
 *
 * gma3_library/
 *   datapools/
 *     macros/
 *       Macro_{macroId}_{cleanTitle}.xml
 *     timecodes/
 *       Timecode_{timecodeId}_{cleanTitle}.xml
 *     appearances/
 *       Appearances_{cleanTitle}.xml
 * scripts/
 *   import_show.cmd
 * README_MA3_USB_IMPORT.txt
 */
export async function buildGrandMa3UsbZip(
  show: CompiledShow,
  config: ExportConfiguration,
  options: ZipExportOptions = {}
): Promise<Blob> {
  const zip = new JSZip();
  const cleanTitle = config.songTitle.replace(/[^a-zA-Z0-9_-]/g, '_');

  const bundle = generateEnhancedMa3ExportBundle(show, {
    includeCueAppearances: options.includeCueAppearances ?? true,
    baseAppearancePoolId: options.baseAppearancePoolId ?? 101,
    includeMarkerTrack: options.includeMarkerTrack ?? true,
  });

  // Folder 1: gma3_library/datapools/macros/
  const macrosFolder = zip.folder('gma3_library/datapools/macros');
  macrosFolder?.file(`Macro_${config.macroId}_${cleanTitle}.xml`, bundle.macroXml);

  // Folder 2: gma3_library/datapools/timecodes/
  const timecodesFolder = zip.folder('gma3_library/datapools/timecodes');
  timecodesFolder?.file(`Timecode_${config.timecodeId}_${cleanTitle}.xml`, bundle.timecodeXml);

  // Folder 3: gma3_library/datapools/appearances/
  if (options.includeCueAppearances !== false && bundle.appearances) {
    const appearancesFolder = zip.folder('gma3_library/datapools/appearances');
    const appearanceXml = [
      `<?xml version="1.0" encoding="UTF-8"?>`,
      `<GMA3 DataVersion="2.5.0.0">`,
      `    <!-- Generated by CueForge for grandMA3 2.5.x -->`,
      `    <AppearancePool Name="${cleanTitle}_Appearances">`,
      ...Object.values(bundle.appearances).map(
        (app) =>
          `        <Appearance Index="${app.poolId}" Name="${app.name}" BackR="${app.rgb.r}" BackG="${app.rgb.g}" BackB="${app.rgb.b}" BackAlpha="255" Color="${app.ma3ColorRgba}" />`
      ),
      `    </AppearancePool>`,
      `</GMA3>`,
    ].join('\n');
    appearancesFolder?.file(`Appearances_${cleanTitle}.xml`, appearanceXml);
  }

  // Folder 4: scripts/
  const scriptsFolder = zip.folder('scripts');
  scriptsFolder?.file(`${cleanTitle}_commands.cmd`, bundle.macroCommandText);

  // Readme instructions
  const readmeContent = `================================================================================
CueForge — grandMA3 2.5.x Show Import Instructions
Show: ${config.songTitle}
Sequence: #${config.sequenceId} "${config.sequenceName}"
Timecode: #${config.timecodeId} "${config.timecodeName}"
Macro: #${config.macroId}
Frame Rate: ${config.frameRate} fps
Cues & Events: ${show.cues.length} (Strict 1:1:1 Invariant Guaranteed)
================================================================================

HOW TO IMPORT INTO GRANDMA3 (CONSOLE OR ONPC):

1. EXTRACT TO USB DRIVE:
   Extract this ZIP directly to the root of your USB drive formatted in FAT32 or exFAT.
   The drive should contain:
     <USB_ROOT>/gma3_library/datapools/macros/...
     <USB_ROOT>/gma3_library/datapools/timecodes/...
     <USB_ROOT>/gma3_library/datapools/appearances/...

2. INSERT USB INTO CONSOLE / SELECT DRIVE:
   Open the command line in grandMA3 and enter:
     SelectDrive 2
   (Or run "ListDrive" to identify your USB drive number, typically 2 or 3).

3. IMPORT MACRO & BUILD SHOW:
   Run the following command to import the setup macro:
     Import Macro ${config.macroId} "Macro_${config.macroId}_${cleanTitle}" /Drive 2

   Then execute Macro ${config.macroId} by pressing it or typing:
     Go Macro ${config.macroId}

   This will automatically:
     a) Create Sequence #${config.sequenceId} with all ${show.cues.length} cues named and ordered.
     b) Create Timecode Show #${config.timecodeId} with the sequence assigned.
     c) Create all ${show.events.length} timecode GO events at exact marker timestamps.
     d) Link Appearance pool objects with color coding.

4. DIRECT TIMECODE POOL IMPORT (ALTERNATIVE):
   If you prefer to import the Timecode object directly:
     Import Timecode ${config.timecodeId} "Timecode_${config.timecodeId}_${cleanTitle}" /Drive 2

Generated by CueForge on ${new Date().toISOString()}.
`;

  zip.file('README_MA3_USB_IMPORT.txt', readmeContent);

  return await zip.generateAsync({ type: 'blob' });
}
